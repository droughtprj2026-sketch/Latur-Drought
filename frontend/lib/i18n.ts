const DICTS: Record<Locale, Dict> = { en: EN, hi: HI, mr: MR };

export function t(locale: Locale, key: string): string {
  return DICTS[locale][key] ?? DICTS.en[key] ?? key;
}

/** Translate text that lives outside the dictionaries (the layer catalog in lib/metrics.ts,
 *  for instance). Falls back to the English source string when no entry exists. */
export function tf(locale: Locale, key: string, fallback: string): string {
  return DICTS[locale][key] ?? DICTS.en[key] ?? fallback;
}

/** Stable dictionary key from a free-text English label. */
export function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
}
